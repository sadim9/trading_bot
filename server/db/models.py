# ─── BACKTEST RESULTS ─────────────────────────────────────────────────────────

class BacktestResult(Base):
    """Stored backtest runs with full metrics and equity curves."""
    __tablename__ = "backtest_results"

    id: Mapped[str]      = mapped_column(UUID(as_uuid=False), primary_key=True, default=_uuid)
    user_id: Mapped[str] = mapped_column(UUID(as_uuid=False), ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True)

    name: Mapped[Optional[str]]  = mapped_column(String(100), nullable=True)
    symbols: Mapped[list]        = mapped_column(JSON, nullable=False)     # ["AAPL", "GOOGL"]
    interval: Mapped[str]        = mapped_column(String(10), nullable=False)
    period: Mapped[str]          = mapped_column(String(20), nullable=False)
    data_source: Mapped[str]     = mapped_column(String(50), nullable=False)

    config_json: Mapped[dict]    = mapped_column(JSON, nullable=False)     # full BotConfig snapshot
    metrics_json: Mapped[dict]   = mapped_column(JSON, nullable=False)     # per-symbol metrics
    equity_curve: Mapped[Optional[list]] = mapped_column(JSON, nullable=True)   # [{date, equity}, ...]
    trades_summary: Mapped[Optional[list]] = mapped_column(JSON, nullable=True)

    initial_capital: Mapped[float]       = mapped_column(Float, nullable=False)
    final_equity: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    total_return_pct: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    sharpe_ratio: Mapped[Optional[float]]     = mapped_column(Float, nullable=True)
    max_drawdown_pct: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    win_rate_pct: Mapped[Optional[float]]     = mapped_column(Float, nullable=True)

    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=_now, nullable=False, index=True)
    duration_seconds: Mapped[Optional[float]] = mapped_column(Float, nullable=True)

    user: Mapped[User] = relationship("User", back_populates="backtest_results")


# ─── AUDIT LOGS ───────────────────────────────────────────────────────────────

class AuditLog(Base):
    """Immutable security and activity audit trail."""
    __tablename__ = "audit_logs"

    id: Mapped[str]               = mapped_column(UUID(as_uuid=False), primary_key=True, default=_uuid)
    user_id: Mapped[Optional[str]] = mapped_column(UUID(as_uuid=False), ForeignKey("users.id", ondelete="SET NULL"), nullable=True, index=True)

    action: Mapped[str]          = mapped_column(String(100), nullable=False, index=True)
    resource: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    resource_id: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    details: Mapped[Optional[dict]]    = mapped_column(JSON, nullable=True)
    ip_address: Mapped[Optional[str]]  = mapped_column(String(45), nullable=True)
    user_agent: Mapped[Optional[str]]  = mapped_column(String(255), nullable=True)
    status: Mapped[str]                = mapped_column(String(20), default="success", nullable=False)  # success | failure
    created_at: Mapped[datetime]       = mapped_column(DateTime(timezone=True), default=_now, nullable=False, index=True)

    user: Mapped[Optional[User]] = relationship("User", back_populates="audit_logs")

    __table_args__ = (
        Index("ix_audit_logs_created_at", "created_at"),
        Index("ix_audit_logs_action_status", "action", "status"),
    )
